const s2tMap = new Map<string, string>();
const t2sMap = new Map<string, string>();
for (const pair of S2T_TOKEN_LIST) {
  if (pair.length !== 2) continue;
  const s = pair[0]!;
  const t = pair[1]!;
  if (s !== t) {
    if (!s2tMap.has(s)) s2tMap.set(s, t);
    if (!t2sMap.has(t)) t2sMap.set(t, s);
  }
}

/**
 * Converts Simplified Chinese UI/stat text to idiomatic International PoE
 * Traditional Chinese (繁體中文).
 */
export function toTraditionalZh(input: string): string {
  if (!input) return input;
  let out = input;
  for (const [cn, tw] of CN_TO_TW_PHRASES) {
    if (out.includes(cn)) {
      out = out.split(cn).join(tw);
    }
  }
  let mapped = '';
  for (const ch of out) {
    mapped += s2tMap.get(ch) ?? ch;
  }
  return mapped;
}

/**
 * Normalizes Traditional Chinese item/stat text into Simplified Chinese so
 * existing Chinese item & modifier parsers accept both CN and TW clients.
 */
export function toSimplifiedZh(input: string): string {
  if (!input) return input;
  let out = input;
  for (const [tw, cn] of TW_TO_CN_PHRASES) {
    if (out.includes(tw)) {
      out = out.split(tw).join(cn);
    }
  }
  let mapped = '';
  for (const ch of out) {
    mapped += t2sMap.get(ch) ?? ch;
  }
  return mapped;
}
